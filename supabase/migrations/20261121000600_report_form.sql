-- Citizen report form: photos, issue type, location, landmark, duplicates, private contact phone.

-- Uploaded photos. Bytes live in Supabase Storage (bucket report-photos, public) or, when no S3 keys are
-- configured, in UPLOAD_DIR on the API host. EXIF is read into these columns, then stripped from the stored file.
create table photos (
  photo_id     text primary key,  -- uuid generated by the API
  storage      text not null check (storage in ('supabase', 'local')),
  content_type text not null check (content_type in ('image/jpeg', 'image/png', 'image/webp')),  -- as stored
  original_content_type text not null check (original_content_type in ('image/jpeg', 'image/png', 'image/webp', 'image/heic')),
  size_bytes   integer not null check (size_bytes between 1 and 8388608),
  width        integer,
  height       integer,
  taken_at     timestamp,          -- EXIF DateTimeOriginal (camera local time, IST)
  exif_lat     double precision,
  exif_lon     double precision,
  storage_path text not null,      -- object key in the bucket / file name in UPLOAD_DIR
  created_at   timestamptz not null default now()
);

alter table citizen_reports
  add column issue_type text check (issue_type in
    ('pothole', 'waterlogging', 'open_manhole', 'broken_paver', 'cave_in', 'choked_drain', 'other')),
  add column location_lat        double precision check (location_lat between -90 and 90),
  add column location_lon        double precision check (location_lon between -180 and 180),
  add column location_accuracy_m numeric check (location_accuracy_m >= 0),
  add column location_source     text check (location_source in ('gps', 'map_pin', 'exif', 'landmark', 'manual')),
  add column landmark            text check (char_length(landmark) <= 200),
  add column duplicate_of        bigint references citizen_reports (id),
  add column linked_work_order_id text references work_orders (work_order_id);

create table citizen_report_photos (
  report_id bigint references citizen_reports (id),
  photo_id  text references photos (photo_id),
  position  smallint not null check (position between 1 and 3),
  primary key (report_id, photo_id)
);

-- Contact phone is personal data: separate table, RLS on and NO policy, so the public anon key cannot read it.
create table citizen_report_contacts (
  report_id     bigint primary key references citizen_reports (id),
  contact_phone text not null check (contact_phone ~ '^\+?[0-9 -]{6,20}$')
);

-- photos + report photos: public read (reports are public); contacts: no policy at all.
alter table photos enable row level security;
alter table citizen_report_photos enable row level security;
alter table citizen_report_contacts enable row level security;
create policy "public read" on photos for select to anon, authenticated using (true);
create policy "public read" on citizen_report_photos for select to anon, authenticated using (true);
revoke all on citizen_report_contacts from anon, authenticated;

-- Typical SLA per issue type, from the work orders of the matching work_type.
create or replace view issue_sla with (security_invoker = true) as
select i.issue_type, i.work_type,
       (select percentile_disc(0.5) within group (order by sla_hours) from work_orders w where w.work_type = i.work_type) as sla_hours
from (values ('pothole', 'Pothole'), ('waterlogging', 'Waterlogging'), ('open_manhole', 'Open or broken manhole'),
             ('broken_paver', 'Broken paver blocks'), ('cave_in', 'Road cave-in'),
             ('choked_drain', 'Choked drain / nullah overflow'), ('other', null)) as i(issue_type, work_type);
